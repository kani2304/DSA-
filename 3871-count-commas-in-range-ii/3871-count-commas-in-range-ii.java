class Solution {
    public long countCommas(long n) {
        long count = 0;

        if(n > 999 && n <= 999999)
        {
            count = n - 999;
        }

        if(n > 999999 && n <= 999999999)
        {
            count = 999000 + (n - 999999) * 2;
        }

        if(n > 999999999 && n <= 999999999999L)
        {
            count = 999000 + (999000000 * 2) + (n - 999999999) * 3;
        }

        if(n > 999999999999L && n <= 999999999999999L)
        {
            count = 999000
                  + (999000000 * 2)
                  + (999000000000L) * 3
                  + (n - 999999999999L) * 4;
        }

        if(n > 999999999999999L && n <= 999999999999999999L)
        {
            count = 999000
                  + (999000000 * 2)
                  + (999000000000L) * 3
                  + (999000000000000L) * 4
                  + (n - 999999999999999L) * 5;
        }

        if(n > 999999999999999999L)
        {
            count = 999000
                  + (999000000 * 2)
                  + (999000000000L) * 3
                  + (999000000000000L) * 4
                  + (999000000000000000L) * 5
                  + (n - 999999999999999999L) * 6;
        }

        return count;
    }
}